export const EXACT_APPLICATION_PATHS: readonly string[] = exactApplicationPaths;

export function isKnownApplicationPath(path: string) {
  return exactApplicationPathSet.has(path) || dynamicApplicationPathPatterns.some(pattern => pattern.test(path));
}
